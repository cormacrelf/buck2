import './style.css';
import {messages} from './messages.js';

// The count is page state. A hot update of `messages.js` or `style.css` keeps it; an edit to
// this file reloads the page and resets it.
let count = 0;

const app = document.querySelector('#app');
app.innerHTML = `
  <h1>buck2 dev + Vite</h1>
  <ul id="messages"></ul>
  <button id="count"></button>
`;

function renderMessages(list) {
  document.querySelector('#messages').innerHTML = list
    .map(m => `<li>${m}</li>`)
    .join('');
}

function renderCount() {
  document.querySelector('#count').textContent = `Clicked ${count} times`;
}

document.querySelector('#count').addEventListener('click', () => {
  count += 1;
  renderCount();
});

renderMessages(messages);
renderCount();

if (import.meta.hot) {
  // `messages.js` is generated by buck2 from `data/messages.json`.
  import.meta.hot.accept('./messages.js', module => renderMessages(module.messages));
}
