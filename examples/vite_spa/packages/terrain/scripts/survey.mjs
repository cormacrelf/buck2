#!/usr/bin/env node
// Turns terrain.json into a heightmap, as a typed TypeScript module.
//
//   node scripts/survey.mjs <input.json> <output.ts> [--min-ms N]
//
// The heightmap is fractal noise with some smoothing, seeded from the input, so the output depends
// only on the input. `--min-ms` makes the run take at least N milliseconds. The buck2 build passes
// 5000, so that it stands in for a slow generator (a GIS pipeline, a protobuf compiler on a big
// schema). That makes it easy to see that only the page that imports the module waits for it.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname } from 'node:path';

const start = performance.now();
const [input, output, ...rest] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: survey.mjs <input.json> <output.ts> [--min-ms N]');
  process.exit(2);
}
const minMs = rest[0] === '--min-ms' ? Number(rest[1]) : 0;

const data = JSON.parse(readFileSync(input, 'utf8'));
const { name, seed, width, height, octaves, smoothing, seaLevel } = data;

// mulberry32
let state = seed >>> 0;
function random() {
  state = (state + 0x6d2b79f5) >>> 0;
  let t = state;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

// Value noise: a random lattice, interpolated smoothly, summed over octaves.
const values = new Float64Array(width * height);
let amplitude = 1;
for (let o = 0; o < octaves; o++) {
  const cell = Math.max(2, Math.round(Math.min(width, height) / 2 ** (o + 1)));
  const gw = Math.ceil(width / cell) + 2;
  const gh = Math.ceil(height / cell) + 2;
  const grid = Float64Array.from({ length: gw * gh }, random);
  for (let y = 0; y < height; y++) {
    const gy = y / cell, y0 = Math.floor(gy), fy = gy - y0, sy = fy * fy * (3 - 2 * fy);
    for (let x = 0; x < width; x++) {
      const gx = x / cell, x0 = Math.floor(gx), fx = gx - x0, sx = fx * fx * (3 - 2 * fx);
      const a = grid[y0 * gw + x0], b = grid[y0 * gw + x0 + 1];
      const c = grid[(y0 + 1) * gw + x0], d = grid[(y0 + 1) * gw + x0 + 1];
      values[y * width + x] += amplitude * (a + (b - a) * sx + (c - a + (a - b - c + d) * sx) * sy);
    }
  }
  amplitude /= 2;
}

// Box blur passes, for rounder hills.
for (let pass = 0; pass < smoothing; pass++) {
  const next = new Float64Array(values.length);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      let sum = 0, n = 0;
      for (let dy = -1; dy <= 1; dy++) {
        for (let dx = -1; dx <= 1; dx++) {
          const xx = x + dx, yy = y + dy;
          if (xx >= 0 && xx < width && yy >= 0 && yy < height) {
            sum += values[yy * width + xx];
            n++;
          }
        }
      }
      next[y * width + x] = sum / n;
    }
  }
  values.set(next);
}

let lo = Infinity, hi = -Infinity;
for (const v of values) {
  lo = Math.min(lo, v);
  hi = Math.max(hi, v);
}
// Metres, 0 to 1000.
const heights = Array.from(values, (v) => Math.round(((v - lo) / (hi - lo)) * 1000));

const rows = [];
for (let y = 0; y < height; y++) rows.push('  ' + heights.slice(y * width, (y + 1) * width).join(',') + ',');
const lines = [
  `// Generated by scripts/survey.mjs from ${basename(input)}. Do not edit.`,
  '',
  `export const NAME = ${JSON.stringify(name)};`,
  `export const WIDTH = ${width};`,
  `export const HEIGHT = ${height};`,
  `export const SEA_LEVEL = ${Math.round(seaLevel * 1000)};`,
  '',
  '// Metres above the lowest point, row by row from the north-west corner.',
  'export const HEIGHTS: readonly number[] = [',
  ...rows,
  '];',
  '',
];
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, lines.join('\n'));

const remaining = minMs - (performance.now() - start);
if (remaining > 0) Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, remaining);
