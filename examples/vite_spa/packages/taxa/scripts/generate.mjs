#!/usr/bin/env node
// Turns taxa.json into a typed TypeScript module.
//
//   node scripts/generate.mjs <input.json> <output.ts>
//
// The output depends only on the input file, so running it twice gives the
// same bytes. It validates as it goes and exits non-zero on bad data rather
// than writing a module that would fail to typecheck later.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: generate.mjs <input.json> <output.ts>');
  process.exit(2);
}

const STATUSES = ['common', 'local', 'scarce'];
const data = JSON.parse(readFileSync(input, 'utf8'));
const groupIds = Object.keys(data.groups).sort();

const errors = [];
const seen = new Set();
for (const [i, taxon] of data.taxa.entries()) {
  if (!/^[a-z]+(-[a-z]+)+$/.test(taxon.id)) errors.push(`taxa[${i}]: bad id ${taxon.id}`);
  if (seen.has(taxon.id)) errors.push(`taxa[${i}]: duplicate id ${taxon.id}`);
  seen.add(taxon.id);
  if (!groupIds.includes(taxon.group)) errors.push(`taxa[${i}]: unknown group ${taxon.group}`);
  if (!STATUSES.includes(taxon.status)) errors.push(`taxa[${i}]: unknown status ${taxon.status}`);
}
if (errors.length > 0) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const taxa = [...data.taxa].sort((a, b) => a.id.localeCompare(b.id));
const union = (values) => values.map((v) => `  | ${JSON.stringify(v)}`).join('\n');
const lines = [
  `// Generated by scripts/generate.mjs from ${input}. Do not edit.`,
  '',
  `export type GroupId =\n${union(groupIds)};`,
  '',
  `export type TaxonId =\n${union(taxa.map((t) => t.id))};`,
  '',
  `export type Status =\n${union(STATUSES)};`,
  '',
  'export interface Group {',
  '  readonly id: GroupId;',
  '  readonly label: string;',
  '  readonly colour: string;',
  '}',
  '',
  'export interface Taxon {',
  '  readonly id: TaxonId;',
  '  readonly scientific: string;',
  '  readonly common: string;',
  '  readonly group: GroupId;',
  '  readonly status: Status;',
  '}',
  '',
  'export const GROUPS: Readonly<Record<GroupId, Group>> = {',
  ...groupIds.map((id) => {
    const g = data.groups[id];
    return `  ${JSON.stringify(id)}: { id: ${JSON.stringify(id)}, label: ${JSON.stringify(g.label)}, colour: ${JSON.stringify(g.colour)} },`;
  }),
  '};',
  '',
  'export const TAXA: readonly Taxon[] = [',
  ...taxa.map(
    (t) =>
      `  { id: ${JSON.stringify(t.id)}, scientific: ${JSON.stringify(t.scientific)}, common: ${JSON.stringify(t.common)}, group: ${JSON.stringify(t.group)}, status: ${JSON.stringify(t.status)} },`,
  ),
  '];',
  '',
  `export const TAXON_COUNT = ${taxa.length};`,
  '',
];

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, lines.join('\n'));
